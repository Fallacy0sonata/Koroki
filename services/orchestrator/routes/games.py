"""
Game session routes.

POST /v1/games/chess/start   — start or restart a chess game
POST /v1/games/chess/move    — submit a move, get Koroki's response + commentary
GET  /v1/games/chess/state   — current board state
POST /v1/games/chess/resign  — resign the active game
POST /v1/games/decide        — visual-game decision cycle (Stage 2: she plays)

Commentary is generated by a self-call to /v1/chat with game_event_context set,
so it goes through the real brain with full personality.  defer_tts=True means
the TTS job is created but we discard it here (chess is text-only).

/games/decide is the captain's S3-structured play cycle (gaming-eyes ranking,
docs/master_queue.md): scene + rolling state doc in → STATE/DO/SAY out. Her
felt-state rides along, so her body colors her play — tired Koroki plays lazy.
"""
